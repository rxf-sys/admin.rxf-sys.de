/**
 * Generates apps/server/src/plugins.generated.ts from packages/plugins/<id>/manifest.json (ADR 0003).
 * The registry holds manifests as data plus lazy loaders, so listing the catalog loads no plugin code.
 * `--check` fails when the committed file is out of date (run in CI via `pnpm lint`).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pluginManifest } from '../packages/sdk/src/manifest.ts';

const root = new URL('..', import.meta.url).pathname;
const pluginsDir = join(root, 'packages/plugins');
const outFile = join(root, 'apps/server/src/plugins.generated.ts');
const serverDeps = JSON.parse(readFileSync(join(root, 'apps/server/package.json'), 'utf8')).dependencies ?? {};

const entries = readdirSync(pluginsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()
  .map((dir) => {
    const manifest = pluginManifest.parse(JSON.parse(readFileSync(join(pluginsDir, dir, 'manifest.json'), 'utf8')));
    const pkg = JSON.parse(readFileSync(join(pluginsDir, dir, 'package.json'), 'utf8')).name as string;
    if (manifest.id !== dir)
      throw new Error(`packages/plugins/${dir}: manifest id "${manifest.id}" must match the directory`);
    if (pkg !== `@rxf/plugin-${manifest.id}`)
      throw new Error(`packages/plugins/${dir}: package must be named @rxf/plugin-${manifest.id}`);
    if (!serverDeps[pkg]) throw new Error(`apps/server/package.json must depend on ${pkg}`);
    return { manifest, pkg };
  });

const body = entries
  .map(
    ({ manifest, pkg }) =>
      `  {\n    manifest: ${JSON.stringify(manifest)},\n    load: () => import('${pkg}/server'),\n  },`,
  )
  .join('\n');

const output = `// Generated by tooling/generate-plugin-registry.ts from packages/plugins/*/manifest.json. Do not edit.
import type { PluginManifest, ServerPlugin } from '@rxf/sdk';

export interface RegisteredPlugin {
  manifest: PluginManifest;
  load: () => Promise<{ default: ServerPlugin }>;
}

export const pluginRegistry: readonly RegisteredPlugin[] = [
${body}
];
`;

if (process.argv.includes('--check')) {
  if (readFileSync(outFile, 'utf8') !== output) {
    console.error('apps/server/src/plugins.generated.ts is out of date; run `pnpm generate:plugins`');
    process.exit(1);
  }
} else {
  writeFileSync(outFile, output);
}
