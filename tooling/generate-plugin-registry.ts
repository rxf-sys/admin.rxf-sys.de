/**
 * Generates the plugin registries from packages/plugins/<id>/manifest.json (ADR 0003):
 * - apps/server/src/plugins.generated.ts: manifests as data plus lazy loaders of `./server`, so listing the
 *   catalog loads no plugin code;
 * - apps/web/src/plugins.generated.ts: lazy loaders of `./web`, which Vite turns into one chunk per plugin.
 * `--check` fails when a committed file is out of date (run in CI via `pnpm lint`).
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pluginManifest } from '../packages/sdk/src/manifest.ts';

const root = new URL('..', import.meta.url).pathname;
const pluginsDir = join(root, 'packages/plugins');
const serverFile = join(root, 'apps/server/src/plugins.generated.ts');
const webFile = join(root, 'apps/web/src/plugins.generated.ts');
const depsOf = (app: string): Record<string, string> =>
  JSON.parse(readFileSync(join(root, app, 'package.json'), 'utf8')).dependencies ?? {};
const serverDeps = depsOf('apps/server');
const webDeps = depsOf('apps/web');

const entries = readdirSync(pluginsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()
  .map((dir) => {
    const manifest = pluginManifest.parse(JSON.parse(readFileSync(join(pluginsDir, dir, 'manifest.json'), 'utf8')));
    const pkgJson = JSON.parse(readFileSync(join(pluginsDir, dir, 'package.json'), 'utf8'));
    const pkg = pkgJson.name as string;
    const hasWeb = pkgJson.exports?.['./web'] !== undefined;
    if (manifest.id !== dir)
      throw new Error(`packages/plugins/${dir}: manifest id "${manifest.id}" must match the directory`);
    if (pkg !== `@rxf/plugin-${manifest.id}`)
      throw new Error(`packages/plugins/${dir}: package must be named @rxf/plugin-${manifest.id}`);
    if (!serverDeps[pkg]) throw new Error(`apps/server/package.json must depend on ${pkg}`);
    if (hasWeb && !webDeps[pkg]) throw new Error(`apps/web/package.json must depend on ${pkg}`);
    return { manifest, pkg, hasWeb };
  });

const serverBody = entries
  .map(
    ({ manifest, pkg }) =>
      `  {\n    manifest: ${JSON.stringify(manifest)},\n    load: () => import('${pkg}/server'),\n  },`,
  )
  .join('\n');

const serverOutput = `// Generated by tooling/generate-plugin-registry.ts from packages/plugins/*/manifest.json. Do not edit.
import type { PluginManifest, ServerPlugin } from '@rxf/sdk';

export interface RegisteredPlugin {
  manifest: PluginManifest;
  load: () => Promise<{ default: ServerPlugin }>;
}

export const pluginRegistry: readonly RegisteredPlugin[] = [
${serverBody}
];
`;

const webBody = entries
  .filter((entry) => entry.hasWeb)
  .map(({ manifest, pkg }) => `  '${manifest.id}': () => import('${pkg}/web'),`)
  .join('\n');

const webOutput = `// Generated by tooling/generate-plugin-registry.ts from packages/plugins/*/manifest.json. Do not edit.
import type { WebPlugin } from '@rxf/web-sdk';

/** Only dynamic imports: plugin code never lands in the entry chunk (ADR 0003, checked in CI). */
export const webPluginRegistry: Readonly<Record<string, () => Promise<{ default: WebPlugin }>>> = {
${webBody}
};
`;

const outputs: [string, string][] = [
  [serverFile, serverOutput],
  [webFile, webOutput],
];

if (process.argv.includes('--check')) {
  const stale = outputs.filter(([file, content]) => !existsSync(file) || readFileSync(file, 'utf8') !== content);
  for (const [file] of stale) console.error(`${file.slice(root.length)} is out of date; run \`pnpm generate:plugins\``);
  if (stale.length > 0) process.exit(1);
} else {
  for (const [file, content] of outputs) writeFileSync(file, content);
}
